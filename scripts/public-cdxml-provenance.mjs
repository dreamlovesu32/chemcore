import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

export const GALLERY_PROVENANCE_SCHEMA = "chemsema.public-cdxml-gallery-provenance.v1";

function sha256Bytes(bytes) {
  return crypto.createHash("sha256").update(bytes).digest("hex");
}

export function sha256File(filePath) {
  return sha256Bytes(fs.readFileSync(filePath));
}

export function publicCdxmlCliCandidates(
  repoRoot,
  explicitPath = null,
  platform = process.platform,
) {
  const suffix = platform === "win32" ? ".exe" : "";
  return [
    explicitPath,
    path.join(repoRoot, "target", "release", `chemsema-cli${suffix}`),
    path.join(repoRoot, "target", "debug", `chemsema-cli${suffix}`),
  ].filter(Boolean);
}

function cliVersion(cliPath) {
  return JSON.parse(execFileSync(cliPath, ["version"], {
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
  }));
}

function git(repoRoot, args, encoding = "utf8") {
  return execFileSync("git", args, {
    cwd: repoRoot,
    encoding,
    maxBuffer: 256 * 1024 * 1024,
  });
}

export function repositoryState(repoRoot) {
  const head = git(repoRoot, ["rev-parse", "HEAD"]).trim();
  const diff = git(repoRoot, ["diff", "--binary", "HEAD", "--"], null);
  const untracked = git(
    repoRoot,
    ["ls-files", "--others", "--exclude-standard", "-z"],
  ).split("\0").filter(Boolean).sort();
  const digest = crypto.createHash("sha256");
  digest.update(`head\0${head}\0`);
  digest.update("diff\0");
  digest.update(diff);
  for (const relativePath of untracked) {
    digest.update(`untracked\0${relativePath.replaceAll("\\", "/")}\0`);
    digest.update(fs.readFileSync(path.join(repoRoot, relativePath)));
  }
  return {
    head,
    dirty: diff.length > 0 || untracked.length > 0,
    untrackedFiles: untracked,
    identity: digest.digest("hex"),
  };
}

function corpusSources(corpusRoot, corpusManifest) {
  return corpusManifest.sources.map((source) => {
    const sourceRoot = path.join(corpusRoot, source.id);
    const actualRevision = git(sourceRoot, ["rev-parse", "HEAD"]).trim();
    return {
      id: source.id,
      expectedRevision: source.revision,
      actualRevision,
    };
  });
}

export function collectGalleryProvenance({
  repoRoot,
  cliPath,
  corpusRoot,
  corpusManifestPath,
  roundtripReportPath,
  verifyConsistency = true,
}) {
  const resolvedRepoRoot = path.resolve(repoRoot);
  const resolvedCliPath = path.resolve(cliPath);
  const resolvedCorpusRoot = path.resolve(corpusRoot);
  const resolvedCorpusManifestPath = path.resolve(corpusManifestPath);
  const resolvedRoundtripReportPath = path.resolve(roundtripReportPath);
  const corpusManifest = JSON.parse(fs.readFileSync(resolvedCorpusManifestPath, "utf8"));
  const roundtripReport = JSON.parse(fs.readFileSync(resolvedRoundtripReportPath, "utf8"));
  const sources = corpusSources(resolvedCorpusRoot, corpusManifest);
  const repository = repositoryState(resolvedRepoRoot);
  const version = cliVersion(resolvedCliPath);
  if (verifyConsistency && version.buildIdentity !== repository.identity) {
    throw new Error(
      `Public CDXML CLI build identity ${version.buildIdentity ?? "(missing)"} does not match `
      + `repository identity ${repository.identity}. Build it with `
      + "`node scripts/build-public-cdxml-cli.mjs` before generating canonical artifacts.",
    );
  }
  const cliSha256 = sha256File(resolvedCliPath);
  if (verifyConsistency && (
      roundtripReport.repositoryIdentity !== repository.identity
      || roundtripReport.cli?.buildIdentity !== repository.identity
      || roundtripReport.cli?.sha256 !== cliSha256
  )) {
    throw new Error(
      "Public CDXML roundtrip report was not generated by the current repository/CLI identity. "
      + "Regenerate it before rendering the gallery.",
    );
  }
  const revisionMismatch = sources.find(
    (source) => source.actualRevision !== source.expectedRevision,
  );
  if (verifyConsistency && revisionMismatch) {
    throw new Error(
      `Public corpus source ${revisionMismatch.id} is at ${revisionMismatch.actualRevision}, `
      + `expected ${revisionMismatch.expectedRevision}`,
    );
  }
  return {
    schema: GALLERY_PROVENANCE_SCHEMA,
    repository: {
      root: resolvedRepoRoot,
      ...repository,
    },
    cli: {
      path: resolvedCliPath,
      sha256: cliSha256,
      buildIdentity: version.buildIdentity,
      version: version.version,
    },
    corpus: {
      root: resolvedCorpusRoot,
      manifestPath: resolvedCorpusManifestPath,
      manifestSha256: sha256File(resolvedCorpusManifestPath),
      sources,
    },
    roundtripReport: {
      path: resolvedRoundtripReportPath,
      sha256: sha256File(resolvedRoundtripReportPath),
    },
  };
}

export function provenanceMismatches(recorded, current) {
  if (recorded?.schema !== GALLERY_PROVENANCE_SCHEMA) {
    return ["missing-or-unsupported-provenance"];
  }
  const mismatches = [];
  if (recorded.repository?.identity !== current.repository?.identity) {
    mismatches.push("repository-state");
  }
  if (recorded.cli?.sha256 !== current.cli?.sha256) {
    mismatches.push("cli-binary");
  }
  if (recorded.cli?.buildIdentity !== recorded.repository?.identity) {
    mismatches.push("recorded-cli-source-mismatch");
  }
  if (recorded.cli?.buildIdentity !== current.cli?.buildIdentity) {
    mismatches.push("cli-build-identity");
  }
  if (recorded.corpus?.manifestSha256 !== current.corpus?.manifestSha256) {
    mismatches.push("corpus-manifest");
  }
  const currentSources = new Map(
    (current.corpus?.sources ?? []).map((source) => [source.id, source]),
  );
  for (const source of recorded.corpus?.sources ?? []) {
    if (currentSources.get(source.id)?.actualRevision !== source.actualRevision) {
      mismatches.push(`corpus-source:${source.id}`);
    }
  }
  if (recorded.roundtripReport?.sha256 !== current.roundtripReport?.sha256) {
    mismatches.push("roundtrip-report");
  }
  return mismatches;
}

export function collectCurrentGalleryProvenance(recorded) {
  if (recorded?.schema !== GALLERY_PROVENANCE_SCHEMA) return null;
  return collectGalleryProvenance({
    repoRoot: recorded.repository.root,
    cliPath: recorded.cli.path,
    corpusRoot: recorded.corpus.root,
    corpusManifestPath: recorded.corpus.manifestPath,
    roundtripReportPath: recorded.roundtripReport.path,
    verifyConsistency: false,
  });
}
